test('exportar: planilha do contador, CSVs, backup e relatório para imprimir', async ({ page }) => {
  await loadSample(page)
  await page.goto('/#/export')
  await page.getByRole('button', { name: 'Ano-calendário' }).click()
  await page.getByRole('option', { name: String(DATA_YEAR) }).click()
  let download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Baixar planilha (.xlsx)' }).click()
  let file = await download
  expect(file.suggestedFilename()).toBe(`lume-ir-${DATA_YEAR}.xlsx`)
  await file.saveAs('test-results/lume-ir.xlsx')

  download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Receitas e despesas' }).click()
  file = await download
  expect(file.suggestedFilename()).toBe(`lume-lancamentos-${DATA_YEAR}.csv`)
  const csv = readFileSync(await file.path(), 'utf8')
  expect(csv.charCodeAt(0)).toBe(0xfeff)
  expect(csv).toContain('Data;Tipo;Categoria')

  download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Baixar backup (.json)' }).click()
  file = await download
  const backup = JSON.parse(readFileSync(await file.path(), 'utf8'))
  expect(backup.app).toBe('lume')
  expect(backup.data.transactions.length).toBeGreaterThan(50)
  await file.saveAs('test-results/backup.json')

  await page.getByRole('button', { name: 'Abrir relatório' }).click()
  await expect(page).toHaveURL(new RegExp(`#/print\\?year=${DATA_YEAR}`))
  await expect(page.getByRole('heading', { name: `Relatório anual ${DATA_YEAR}` })).toBeVisible()
  await expect(page.getByRole('cell', { name: /HGLG11/ })).toBeVisible()
})


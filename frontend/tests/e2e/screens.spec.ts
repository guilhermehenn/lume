test('backup: restaurar arquivo, recusar arquivo inválido e apagar tudo', async ({ page }) => {
  await loadSample(page)
  const saved = (await (await page.request.get('/api/vault/data')).json()) as { data: unknown }
  const file = JSON.stringify({ app: 'lume', format: 1, exportedAt: '2026-11-20T10:00:00.000Z', data: saved.data })

  await page.getByRole('button', { name: 'Apagar tudo' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Apagar tudo' }).click()
  await expect(page.getByText('Dados apagados')).toBeVisible()
  await expect(page.getByText('18 bancos · 24 categorias · nenhum lançamento · nenhuma operação de investimento · nenhum relatório salvo')).toBeVisible()

  await page.locator('input[type=file]').setInputFiles({ name: 'ruim.json', mimeType: 'application/json', buffer: Buffer.from('{"app":"outro"}') })
  await expect(page.getByText('Esse arquivo não é um backup do Lume.')).toBeVisible()

  await page.locator('input[type=file]').setInputFiles({ name: 'lume.json', mimeType: 'application/json', buffer: Buffer.from(file) })
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toContainText('20 de nov. de 2026')
  await dialog.getByRole('button', { name: 'Restaurar backup' }).click()
  await expect(page.getByText('Backup restaurado')).toBeVisible()
  await expect(page.getByText(/18 bancos · 24 categorias · \d{2,} lançamentos/)).toBeVisible()
  // Gravado no cofre: recarregando, continua lá
  await page.reload()
  await expect(page.getByText(/18 bancos · 24 categorias · \d{2,} lançamentos/)).toBeVisible()
})


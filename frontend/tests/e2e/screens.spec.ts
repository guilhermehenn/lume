test('bancos: criar, tornar principal e excluir movendo lançamentos', async ({ page }) => {
  await loadSample(page)
  await page.goto('/#/banks')
  await page.getByRole('button', { name: 'Novo banco' }).click()
  const sheet = page.getByRole('dialog')
  await sheet.getByLabel('Nome').fill('Carteira')
  await sheet.locator('#bank-kind').click()
  await page.getByRole('option', { name: 'Dinheiro em espécie' }).click()
  await sheet.locator('#bank-initial').click()
  await page.keyboard.type('25000')
  await page.keyboard.press('-')
  await expect(sheet.locator('#bank-initial')).toHaveValue(brl('−R$ 250,00'))
  await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByText('Banco salvo')).toBeVisible()
  const carteira = page.getByRole('listitem').filter({ hasText: 'Carteira' })
  await expect(carteira).toContainText('−R$ 250,00')

  await carteira.getByRole('button', { name: 'Mais opções' }).click()
  await page.getByRole('menuitem', { name: 'Tornar principal' }).click()
  await expect(page.getByText('Carteira agora é o principal')).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Principal' })).toHaveCount(1)

  const nubank = page.getByRole('listitem').filter({ hasText: 'Nubank' })
  await nubank.getByRole('button', { name: 'Mais opções' }).click()
  await page.getByRole('menuitem', { name: 'Excluir' }).click()
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toContainText('lançamentos usam este banco')
  // O destino sugerido é o principal; dá para trocar antes de confirmar.
  await expect(dialog.getByRole('button', { name: 'Mover lançamentos para' })).toContainText('Carteira')
  await dialog.getByRole('button', { name: 'Mover lançamentos para' }).click()
  await page.getByRole('option', { name: 'Itaú' }).click()
  await dialog.getByRole('button', { name: 'Mover e excluir' }).click()
  const deletedToast = page.getByText(/^Nubank excluído\. \d+ lançamentos foram para Itaú\.$/).locator('..')
  await expect(deletedToast).toBeVisible()
  await expect(nubank).toHaveCount(0)
  await deletedToast.getByRole('button', { name: 'Desfazer' }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Nubank' })).toHaveCount(1)
})


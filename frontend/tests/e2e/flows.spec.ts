import { brl, expect, mockApi, PASSWORD, pretendNoVaults, skipOnboarding, test, YEAR } from './fixtures'

test.describe('primeiro acesso e Início', () => {
  test('primeiro uso: criar cofre, depois banco principal e saldo inicial', async ({ page }) => {
    await mockApi(page)
    await pretendNoVaults(page)
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Boas-vindas ao Lume' })).toBeVisible()

    // Passo 1: cofre e dono (com validação)
    const vaultName = `Casa ${Date.now() % 1_000_000}`
    await page.getByLabel('Nome do cofre').fill(vaultName)
    await page.getByRole('button', { name: 'Continuar' }).click()
    await expect(page.getByText('Informe seu nome.')).toBeVisible()
    await expect(page.getByText('Digite um e-mail válido.')).toBeVisible()
    await page.getByLabel('Nome', { exact: true }).fill('Guilherme')
    await page.getByLabel('Sobrenome').fill('Henn')
    // Erro de digitação no domínio: o Lume sugere o certo
    await page.getByLabel('E-mail').fill(`novo-${Date.now()}@gmial.com`)
    await page.getByRole('button', { name: /Você quis dizer .*@gmail\.com\?/ }).click()
    await expect(page.getByLabel('E-mail')).toHaveValue(/@gmail\.com$/)
    await page.getByRole('button', { name: 'Continuar' }).click()

    // Passo 2: senha
    await expect(page.getByRole('heading', { name: 'Senha de acesso' })).toBeVisible()
    await page.getByLabel('Senha', { exact: true }).fill('curta')
    await page.getByRole('button', { name: 'Continuar' }).click()
    await expect(page.getByText('Use pelo menos 8 caracteres.')).toBeVisible()
    await page.getByLabel('Senha', { exact: true }).fill(PASSWORD)
    await page.getByLabel('Confirmar senha').fill('outra coisa qualquer')
    await page.getByRole('button', { name: 'Continuar' }).click()
    await expect(page.getByText('As senhas não conferem.')).toBeVisible()
    await page.getByLabel('Confirmar senha').fill(PASSWORD)
    await page.getByRole('button', { name: 'Continuar' }).click()

    // Passo 3: começar do zero
    await page.getByText('Começar do zero').click()
    await page.getByRole('button', { name: 'Criar cofre' }).click()

    // Código de recuperação: aparece uma vez e só dá para seguir depois de confirmar que guardou
    await expect(page.getByRole('heading', { name: 'Guarde seu código de recuperação' })).toBeVisible()
    await expect(page.locator('#recovery-code')).toHaveText(/^[0-9A-Z]{5}(-[0-9A-Z]{5}){3}$/)
    const enter = page.getByRole('button', { name: 'Entrar no cofre' })
    await expect(enter).toBeDisabled()
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Baixar .txt' }).click()
    expect((await download).suggestedFilename()).toMatch(/^lume-codigo-de-recuperacao-casa-\d+\.txt$/)
    await page.getByLabel('Guardei o código em lugar seguro').check()
    await enter.click()

    const sheet = page.getByRole('dialog')
    await expect(sheet.getByText('Boas-vindas ao Lume')).toBeVisible()
    await sheet.locator('#onb-bank').click()
    await page.getByRole('option', { name: 'Itaú' }).click()
    await sheet.locator('#onb-balance').click()
    await page.keyboard.type('150000')
    await expect(sheet.locator('#onb-balance')).toHaveValue(brl('R$ 1.500,00'))
    await sheet.getByRole('button', { name: 'Começar' }).click()
    await expect(page.getByRole('heading', { level: 1 })).toContainText('Guilherme')
    const balances = page.locator('section', { hasText: 'Saldo nos bancos' })
    await expect(balances.getByText('Itaú')).toBeVisible()
    await expect(balances.getByText('R$ 1.500,00').first()).toBeVisible()
    await expect(page.getByText('Salvo no cofre')).toBeVisible()
    // Recarregar continua no cofre, e as boas-vindas não voltam
    await page.reload()
    await expect(page.getByRole('heading', { level: 1 })).toContainText('Guilherme')
    await expect(page.getByText('Boas-vindas ao Lume')).toHaveCount(0)
    await expect(balances.getByText('R$ 1.500,00').first()).toBeVisible()
  })

  test('cotações, indicadores e notícias', async ({ page }) => {
    await mockApi(page)
    await skipOnboarding(page)
    await page.goto('/')
    const market = page.locator('section[aria-labelledby="market-title"]')
    await expect(market.getByText('Dólar')).toBeVisible()
    await expect(market.getByText('R$ 5,43')).toBeVisible()
    await expect(market.getByText('R$ 512.346')).toBeVisible()
    await expect(market.getByText('+2,50%')).toBeVisible()
    await expect(market.getByText('15,00%')).toBeVisible()
    await expect(market.getByText('IPCA')).toBeVisible()
    const link = page.getByRole('link', { name: /Ibovespa fecha em alta/ })
    await expect(link).toHaveAttribute('target', '_blank')
    await expect(link).toHaveAttribute('rel', /noopener/)
  })

  test('sem back-end: aviso amigável no lugar das cotações', async ({ page }) => {
    await mockApi(page, { offline: true })
    await skipOnboarding(page)
    await page.goto('/')
    await expect(page.getByText('Sem conexão com as cotações agora.')).toBeVisible()
    await expect(page.getByText('Não deu para buscar as notícias agora.')).toBeVisible()
  })
})

test.describe('lançamentos', () => {
  test.beforeEach(async ({ page }) => {
    await mockApi(page)
    await skipOnboarding(page)
  })

  test('despesa: valor formatado ao digitar, sugestões, edição, exclusão e desfazer', async ({ page }) => {
    await page.goto('/#/transactions')
    await page.keyboard.press('n')
    const sheet = page.getByRole('dialog')
    await expect(sheet.getByRole('heading', { name: 'Nova despesa' })).toBeVisible()
    const amount = sheet.locator('#entry-amount')
    await expect(amount).toBeFocused()
    await page.keyboard.type('4590')
    await expect(amount).toHaveValue(brl('R$ 45,90'))
    await page.keyboard.press('Backspace')
    await expect(amount).toHaveValue(brl('R$ 4,59'))
    await page.keyboard.type('0')
    await sheet.locator('#entry-counterparty').fill('Padaria Pão Quente')
    await sheet.locator('#entry-category').click()
    await page.getByRole('option', { name: 'Mercado' }).click()
    await sheet.getByRole('radio', { name: 'Pix' }).click()
    await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page.getByText('Despesa salva')).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Nova despesa' })).toBeHidden()

    const row = page.getByRole('button', { name: /Padaria Pão Quente/ })
    await expect(row).toContainText('−R$ 45,90')
    await expect(row).toContainText('Mercado')

    // A próxima despesa sugere o nome e a categoria
    await page.keyboard.press('n')
    await page.keyboard.type('1000')
    await sheet.locator('#entry-counterparty').fill('pada')
    await page.getByRole('option', { name: 'Padaria Pão Quente' }).click()
    await expect(sheet.locator('#entry-category')).toContainText('Mercado')
    // Algo preenchido: cancelar pede confirmação antes de descartar.
    await sheet.getByRole('button', { name: 'Cancelar' }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Descartar' }).click()
    await expect(sheet).toHaveCount(0)

    // Editar
    await row.click()
    await expect(sheet.getByRole('heading', { name: 'Editar despesa' })).toBeVisible()
    await sheet.locator('#entry-amount').click()
    await page.keyboard.press('Backspace')
    await page.keyboard.press('Backspace')
    await page.keyboard.type('00')
    await sheet.getByRole('button', { name: 'Salvar alterações' }).click()
    await expect(page.getByText('Alterações salvas')).toBeVisible()
    await expect(row).toContainText('−R$ 45,00')

    // Excluir e desfazer
    await row.click()
    await sheet.getByRole('button', { name: 'Excluir' }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Excluir' }).click()
    await expect(row).toHaveCount(0)
    await page.getByRole('status').locator(':scope > div', { hasText: 'Lançamento excluído' }).getByRole('button', { name: 'Desfazer' }).click()
    await expect(row).toBeVisible()
  })

  test('validação: campos obrigatórios aparecem juntos', async ({ page }) => {
    await page.goto('/')
    await page.getByRole('button', { name: 'Novo' }).first().click()
    await page.getByRole('menuitem', { name: 'Despesa' }).click()
    const sheet = page.getByRole('dialog')
    await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(sheet.getByText('Digite um valor maior que zero.')).toBeVisible()
    await expect(sheet.getByText('Preencha este campo.')).toBeVisible()
    await expect(sheet.getByText('Escolha uma categoria.')).toBeVisible()
    await expect(sheet.getByRole('heading', { name: 'Nova despesa' })).toBeVisible()
  })

  test('receita: entra no resumo do mês e Ctrl+Enter salva', async ({ page }) => {
    await page.goto('/')
    await page.keyboard.press('n')
    const sheet = page.getByRole('dialog')
    await sheet.getByRole('radio', { name: 'Receita' }).click()
    await expect(sheet.getByRole('heading', { name: 'Nova receita' })).toBeVisible()
    await sheet.locator('#entry-amount').click()
    await page.keyboard.type('820000')
    await sheet.locator('#entry-counterparty').fill('Empresa XYZ')
    await sheet.locator('#entry-category').click()
    await page.getByRole('option', { name: 'Salário' }).click()
    await sheet.locator('#entry-counterparty').press('Control+Enter')
    await expect(page.getByText('Receita salva')).toBeVisible()
    const summary = page.locator('section', { hasText: 'Resumo de' }).first()
    await expect(summary.getByText('R$ 8.200,00').first()).toBeVisible()
    await expect(summary).toContainText('Você guardou 100%')
  })

  test('investimento em ações: ticker, quantidade × preço e código do IR', async ({ page }) => {
    await page.goto('/#/investments')
    await page.getByRole('button', { name: 'Nova operação' }).click()
    const sheet = page.getByRole('dialog')
    await expect(sheet.getByRole('heading', { name: 'Novo investimento' })).toBeVisible()
    await sheet.locator('#inv-type').click()
    await page.getByRole('option', { name: /^Ações/ }).click()
    await sheet.locator('#inv-bank').click()
    await page.getByRole('option', { name: 'XP Investimentos' }).click()
    await sheet.locator('#inv-asset').fill('petr4')
    await expect(sheet.locator('#inv-asset')).toHaveValue('PETR4')
    await sheet.locator('#inv-qty').fill('100')
    await sheet.locator('#inv-price').click()
    await page.keyboard.type('3050')
    await sheet.locator('#inv-fees').click()
    await page.keyboard.type('490')
    await expect(sheet.locator('#entry-amount')).toHaveValue(brl('R$ 3.054,90'))
    await expect(sheet.getByText('Bens e Direitos: Grupo 03 · Código 01')).toBeVisible()
    await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page.getByText('Investimento salvo')).toBeVisible()
    const position = page.getByRole('button', { name: /PETR4/ })
    await expect(position).toContainText('03 · 01')
    await expect(position).toContainText('R$ 3.054,90')
    await expect(position).toContainText('100')

    // Rendimento a partir da carteira
    await position.click()
    await page.getByRole('button', { name: 'Rendimento' }).click()
    await expect(sheet.locator('#inv-asset')).toHaveValue('PETR4')
    await page.keyboard.type('12345')
    await sheet.locator('#inv-earning').click()
    await page.getByRole('option', { name: 'Dividendos' }).click()
    await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page.getByText(`Rendimentos em ${YEAR}`)).toBeVisible()
    await expect(page.locator('section', { hasText: 'Rendimentos em' }).first()).toContainText('R$ 123,45')
  })

  test('Tesouro e CNPJ: título obrigatório e CNPJ verificado', async ({ page }) => {
    await page.goto('/')
    await page.keyboard.press('n')
    const sheet = page.getByRole('dialog')
    await sheet.getByRole('radio', { name: 'Investimento' }).click()
    await page.keyboard.type('100000')
    await sheet.locator('#inv-type').click()
    await page.getByRole('option', { name: 'Tesouro Direto' }).click()
    await sheet.locator('#inv-qty').fill('0,5')
    await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(sheet.getByText('Escolha o título do Tesouro.')).toBeVisible()
    await sheet.locator('#inv-type').click()
    await page.getByRole('option', { name: 'CDB / RDB / LC' }).click()
    await sheet.locator('#inv-cnpj').fill('11222333000182')
    await expect(sheet.locator('#inv-cnpj')).toHaveValue('11.222.333/0001-82')
    await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(sheet.getByText('CNPJ inválido. Confira letras e números.')).toBeVisible()
    await sheet.locator('#inv-cnpj').fill('11222333000181')
    await sheet.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page.getByText('Investimento salvo')).toBeVisible()
  })
})
